import { byteCompare } from "./findings.js";
import { BUILTIN_KINDS, type Config, type Page, sectionHeading } from "./model.js";

const HEADER = "<!-- GENERATED by loredown. Do not edit — rebuild with: npx loredown index -->";

/**
 * Deterministic index generation (SPEC §6): fixed kind order (builtins, then
 * config kinds), byte-order ascending ids, ISO dates, no run timestamps.
 * Identical page set ⇒ byte-identical output.
 */
export function generateIndex(config: Config, pages: readonly Page[]): string {
  const active = pages.filter((p) => p.status === "active");
  const lines: string[] = [
    HEADER,
    "# Lore index",
    `_${active.length} active page${active.length === 1 ? "" : "s"} · schema v${config.schemaVersion}_`,
  ];

  const kindOrder = [...BUILTIN_KINDS, ...config.kinds];
  for (const kind of kindOrder) {
    const inKind = active.filter((p) => p.kind === kind).sort((a, b) => byteCompare(a.id, b.id));
    if (inKind.length === 0) continue;
    lines.push("", `## ${sectionHeading(kind)}`);
    for (const page of inKind) {
      lines.push(`- [[${page.id}]] — ${page.title} (${page.updated})`);
    }
  }

  const inactive = pages
    .filter((p) => p.status !== "active")
    .sort((a, b) => byteCompare(a.id, b.id));
  if (inactive.length > 0) {
    lines.push("", "## Archive");
    for (const page of inactive) {
      if (page.status === "superseded") {
        const successor = pages.find((p) => p.supersedes === page.id);
        lines.push(
          successor === undefined
            ? `- [[${page.id}]] — superseded`
            : `- [[${page.id}]] — superseded by [[${successor.id}]]`,
        );
      } else {
        lines.push(`- [[${page.id}]] — archived`);
      }
    }
  }

  return `${lines.join("\n")}\n`;
}
